const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const colorLines = (colors, theme, indent = "    ") =>
    Object.entries(colors).map(([name, value]) => `${indent}--color-${kebab(name)}: ${value[theme]};`);

const scaleLines = (prefix, obj) => Object.entries(obj).map(([k, v]) => `    --${prefix}-${k}: ${v};`);

// bible: true adds what only the design bible needs. `color-scheme` would restyle the storefront's native controls
// (scrollbars, selects) for dark-OS visitors before the theme consumes the dark tokens, and the print override keeps
// paper output light whichever theme is active.
export function renderScss(tokens, {bible = false} = {}) {
    const {colors, type, space, radius, motion} = tokens;
    const scheme = (value, indent = "    ") => (bible ? [`${indent}color-scheme: ${value};`] : []);
    const out = [
        "// GENERATED by scripts/generate-design-tokens.mjs from docs/design/tokens.json. Do not edit.",
        ":root {",
        ...scheme("light dark"),
        ...colorLines(colors, "light"),
        `    --font-stack: ${type.fontStack};`,
        `    --font-size-base: ${type.baseSize};`,
        `    --line-height-base: ${type.baseLineHeight};`,
        ...scaleLines("font-size", type.scale),
        ...scaleLines("space", space),
        ...scaleLines("radius", radius),
        ...scaleLines("motion", motion),
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        '    :root:not([data-theme="light"]) {',
        ...colorLines(colors, "dark", "        "),
        "    }",
        "}",
        "",
        ':root[data-theme="dark"] {',
        ...scheme("dark"),
        ...colorLines(colors, "dark"),
        "}",
        "",
        ...(bible ? [':root[data-theme="light"] {', ...scheme("light"), "}", ""] : []),
        "@media (prefers-reduced-motion: reduce) {",
        "    :root {",
        ...Object.keys(motion).map((k) => `        --motion-${k}: 0ms;`),
        "    }",
        "}",
        "",
        ...(bible
            ? [
                  "@media print {",
                  '    :root, :root:not([data-theme="light"]), :root[data-theme="dark"], :root[data-theme="light"] {',
                  "        color-scheme: light;",
                  ...colorLines(colors, "light", "        "),
                  "    }",
                  "}",
                  "",
              ]
            : []),
    ];
    return out.join("\n");
}

export function configDrift(tokens, config) {
    const drift = [];
    for (const value of Object.values(tokens.colors)) {
        if (!value.configKey) continue;
        const actual = config.settings[value.configKey];
        if (String(actual).toLowerCase() !== value.light.toLowerCase()) {
            drift.push({key: value.configKey, expected: value.light, actual: String(actual)});
        }
    }
    return drift;
}

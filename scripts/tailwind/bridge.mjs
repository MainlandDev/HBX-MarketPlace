// Scans SCSS settings for top-level $variables and renders a partial that re-emits them as --sv-* custom properties,
// so Tailwind (which runs before libsass and cannot see $vars) can reference them with var().
const stripComments = (scss) => scss.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^[ \t]*\/\/.*$/gm, "");

const DECLARATION = /^\$([\w-]+)\s*:\s*[^;]+;/gm;

export function scanVariables(files) {
    const seen = new Set();
    const duplicates = new Set();
    for (const {text} of files) {
        for (const match of stripComments(text).matchAll(DECLARATION)) {
            if (seen.has(match[1])) duplicates.add(match[1]);
            seen.add(match[1]);
        }
    }
    return {names: [...seen], duplicates: [...duplicates]};
}

// Maps, booleans and null cannot be written as a custom property value (interpolating a map is a compile error).
const MIXIN = [
    "@mixin sv($name, $value) {",
    '    @if $value != null and $value != "" and type-of($value) != "bool" and type-of($value) != "map" and not (type-of($value) == "list" and length($value) == 0) {',
    "        --sv-#{$name}: #{$value};",
    "    }",
    "}",
];

// Merchant settings the SCSS reads directly (`stencilColor("optimizedCheckout-link-color")`) have no $variable, so the variable bridge
// cannot see them. Images and booleans have no custom-property form.
const SETTING_CALL = /\b(stencil(?:Color|Number|String|FontFamily|FontWeight))\(\s*"([^"]+)"/g;

export function scanSettingCalls(files) {
    const seen = new Set();
    const found = [];
    for (const {text} of files) {
        for (const match of stripComments(text).matchAll(SETTING_CALL)) {
            const id = `${match[1]}:${match[2]}`;
            if (seen.has(id)) continue;
            seen.add(id);
            found.push({fn: match[1], key: match[2]});
        }
    }
    return found;
}

// A font setting is read twice, as family and as weight, under one key: the two need different property names.
export const settingName = (fn, key) => (fn === "stencilFontFamily" ? `setting-family-${key}` : fn === "stencilFontWeight" ? `setting-weight-${key}` : `setting-${key}`);

export function renderBridge(names, settings = []) {
    return [
        "// GENERATED by scripts/generate-bridge.mjs from the $variables in assets/scss/settings and the stencil settings read in the SCSS. Do not edit.",
        ...MIXIN,
        "",
        ":root {",
        ...names.map((name) => `    @include sv("${name}", $${name});`),
        ...settings.map(({fn, key}) => `    @include sv("${settingName(fn, key)}", ${fn}("${key}"));`),
        "}",
        "",
    ].join("\n");
}

// The committed file is LF; a Windows checkout with core.autocrlf turns it into CRLF, which must not count as stale.
export const isCurrent = (current, expected) => current.replace(/\r\n/g, "\n") === expected.replace(/\r\n/g, "\n");

export function scanMarkupSettings(files, settings) {
    const seen = new Set();
    const found = [];
    for (const {text} of files) {
        for (const match of text.matchAll(/--sv-setting-([A-Za-z0-9_-]+)/g)) {
            const key = match[1];
            if (seen.has(key) || !(key in settings)) continue;
            seen.add(key);
            found.push({fn: /^#[0-9a-f]{3,8}$/i.test(String(settings[key])) ? "stencilColor" : "stencilString", key});
        }
    }
    return found;
}

// Names a source file reads as var(--sv-NAME): only those $variables need a custom property. Dynamic names do not exist in this code base.
export function scanReferences(files) {
    const used = new Set();
    for (const {text} of files) for (const match of text.matchAll(/--sv-([A-Za-z0-9_-]+)/g)) used.add(match[1]);
    return used;
}

export const onlyReferenced = (names, used) => names.filter((name) => used.has(name));

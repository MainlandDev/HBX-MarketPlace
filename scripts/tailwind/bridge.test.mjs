import {describe, expect, it} from "vitest";
import {isCurrent, renderBridge, scanMarkupSettings, scanSettingCalls, scanVariables} from "./bridge.mjs";

const scan = (...texts) => scanVariables(texts.map((text, i) => ({path: `f${i}.scss`, text})));

describe("scanVariables", () => {
    it("finds top-level declarations, with or without !default", () => {
        const {names} = scan('$color-primary: stencilColor("color-primary");\n$gap: 1rem !default;\n');
        expect(names).toEqual(["color-primary", "gap"]);
    });

    it("ignores indented declarations and commented-out ones", () => {
        const {names} = scan("@if $a {\n    $inner: 1;\n}\n// $line: 1;\n/* $block: 1; */\n$kept: 2;\n");
        expect(names).toEqual(["kept"]);
    });

    it("reads a multi-line value as one variable", () => {
        const {names} = scan("$list: (\n  a,\n  b\n);\n");
        expect(names).toEqual(["list"]);
    });

    it("keeps comma lists (font stacks)", () => {
        expect(scan("$font-family-sans: Arial, sans-serif;\n").names).toEqual(["font-family-sans"]);
    });

    it("returns each name once in first-seen order and reports duplicates", () => {
        const result = scan("$a: 1;\n$b: 2;\n", "$a: 3;\n$c: 4;\n");
        expect(result.names).toEqual(["a", "b", "c"]);
        expect(result.duplicates).toEqual(["a"]);
    });
});

describe("renderBridge", () => {
    const out = renderBridge(["a", "b"]);

    it("has the generated header and the guard mixin", () => {
        expect(out).toContain("// GENERATED by scripts/generate-bridge.mjs");
        expect(out).toContain("@mixin sv($name, $value)");
        for (const skipped of ['!= null', '!= "bool"', '!= "map"', 'length($value) == 0', '$value != ""']) expect(out).toContain(skipped);
    });

    it("includes one entry per name inside :root", () => {
        expect(out).toMatch(/:root \{[\s\S]*@include sv\("a", \$a\);[\s\S]*@include sv\("b", \$b\);/);
    });

    it("is deterministic", () => {
        expect(renderBridge(["a", "b"])).toBe(out);
    });
});

describe("isCurrent", () => {
    it("ignores line-ending differences (a Windows checkout turns the committed LF file into CRLF)", () => {
        expect(isCurrent("a\r\nb\r\n", "a\nb\n")).toBe(true);
        expect(isCurrent("a\nb\n", "a\nb\n")).toBe(true);
    });

    it("still detects real changes and a missing file", () => {
        expect(isCurrent("a\nc\n", "a\nb\n")).toBe(false);
        expect(isCurrent("", "a\n")).toBe(false);
    });
});

describe("scanSettingCalls", () => {
    it("lists each stencil setting read directly in the SCSS once, with the function that reads it", () => {
        const found = scanSettingCalls([
            {path: "a.scss", text: '.a { color: stencilColor("optimizedCheckout-link-color"); font-family: stencilFontFamily("headings"); }\n// stencilColor("commented")\n'},
            {path: "b.scss", text: '.b { color: stencilColor("optimizedCheckout-link-color"); content: stencilString("quote"); w: stencilNumber("gap", em); }'},
        ]);
        expect(found).toEqual([
            {fn: "stencilColor", key: "optimizedCheckout-link-color"},
            {fn: "stencilFontFamily", key: "headings"},
            {fn: "stencilString", key: "quote"},
            {fn: "stencilNumber", key: "gap"},
        ]);
    });

    it("ignores image and boolean settings, which have no custom-property form", () => {
        expect(scanSettingCalls([{path: "a.scss", text: 'a { b: stencilImage("x", 1); c: stencilBoolean("y"); }'}])).toEqual([]);
    });
});

describe("renderBridge with settings", () => {
    it("emits one --sv-setting-<key> property per setting call", () => {
        const out = renderBridge(["a"], [{fn: "stencilColor", key: "label-color"}]);
        expect(out).toContain('@include sv("setting-label-color", stencilColor("label-color"));');
        expect(out).toMatch(/@include sv\("a", \$a\);[\s\S]*setting-label-color/);
    });
});

describe("scanMarkupSettings", () => {
    // A converted rule leaves the SCSS, so its setting would drop out of the bridge while the markup still reads it.
    it("keeps a setting that markup reads as --sv-setting-<key>, choosing the stencil function from the config value", () => {
        const found = scanMarkupSettings(
            [{path: "a.tsx", text: '<p className="text-(--sv-setting-label-color) bg-(--sv-setting-label-backgroundColor) text-(--sv-setting-fontFamily-headings)">'}],
            {"label-color": "#ffffff", "label-backgroundColor": "#ff0000", "fontFamily-headings": "Montserrat_700"},
        );
        expect(found).toEqual([
            {fn: "stencilColor", key: "label-color"},
            {fn: "stencilColor", key: "label-backgroundColor"},
            {fn: "stencilString", key: "fontFamily-headings"},
        ]);
    });

    it("ignores a key that is not in the config", () => {
        expect(scanMarkupSettings([{path: "a.tsx", text: "text-(--sv-setting-nope)"}], {})).toEqual([]);
    });
});

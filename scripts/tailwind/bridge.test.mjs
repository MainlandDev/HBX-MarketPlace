import {describe, expect, it} from "vitest";
import {isCurrent, renderBridge, scanVariables} from "./bridge.mjs";

const scan = (...texts) => scanVariables(texts.map((text, i) => ({path: `f${i}.scss`, text})));

describe("scanVariables", () => {
    it("finds top-level declarations, with or without !default", () => {
        const {names} = scan('$color-primary: stencilColor("color-primary");\n$gap: 1rem !default;\n');
        expect(names).toEqual(["color-primary", "gap"]);
    });

    it("ignores indented declarations and commented-out ones", () => {
        const {names} = scan("@if $a {\n    $inner: 1;\n}\n// $line: 1;\n/* $block: 1; */\n$kept: 2;\n");
        expect(names).toEqual(["kept"]);
    });

    it("reads a multi-line value as one variable", () => {
        const {names} = scan("$list: (\n  a,\n  b\n);\n");
        expect(names).toEqual(["list"]);
    });

    it("keeps comma lists (font stacks)", () => {
        expect(scan("$font-family-sans: Arial, sans-serif;\n").names).toEqual(["font-family-sans"]);
    });

    it("returns each name once in first-seen order and reports duplicates", () => {
        const result = scan("$a: 1;\n$b: 2;\n", "$a: 3;\n$c: 4;\n");
        expect(result.names).toEqual(["a", "b", "c"]);
        expect(result.duplicates).toEqual(["a"]);
    });
});

describe("renderBridge", () => {
    const out = renderBridge(["a", "b"]);

    it("has the generated header and the guard mixin", () => {
        expect(out).toContain("// GENERATED by scripts/generate-bridge.mjs");
        expect(out).toContain("@mixin sv($name, $value)");
        for (const skipped of ['!= null', '!= "bool"', '!= "map"', 'length($value) == 0', '$value != ""']) expect(out).toContain(skipped);
    });

    it("includes one entry per name inside :root", () => {
        expect(out).toMatch(/:root \{[\s\S]*@include sv\("a", \$a\);[\s\S]*@include sv\("b", \$b\);/);
    });

    it("is deterministic", () => {
        expect(renderBridge(["a", "b"])).toBe(out);
    });
});

describe("isCurrent", () => {
    it("ignores line-ending differences (a Windows checkout turns the committed LF file into CRLF)", () => {
        expect(isCurrent("a\r\nb\r\n", "a\nb\n")).toBe(true);
        expect(isCurrent("a\nb\n", "a\nb\n")).toBe(true);
    });

    it("still detects real changes and a missing file", () => {
        expect(isCurrent("a\nc\n", "a\nb\n")).toBe(false);
        expect(isCurrent("", "a\n")).toBe(false);
    });
});
